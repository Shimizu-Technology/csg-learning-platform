async function staff(page: Page, paced = false) {
  await page.goto(`/admin/cohorts/${paced ? ids.paced : ids.program}/students/${paced ? 953 : 951}/learning?qa_user=1`)
  const panel = page.getByRole('region', { name: 'Deadlines and extensions' })
  await expect(panel).toBeVisible()
  await expect(panel.getByLabel('Applies to')).toBeEnabled()
  return panel
}
async function learnerSubmit(page: Page, lesson: number, user = 951, cohort = ids.program) {
  await page.goto(`/lessons/${lesson}?cohort_id=${cohort}&qa_user=${user}`)
  const input = page.getByRole('textbox', { name: 'Your answer, rich text' })
  await expect(input).toBeEnabled()
  await input.fill('Written during deadline review')
  await page.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(page.getByText(/Waiting for review/).first()).toBeVisible()
  await page.reload()
  await expect(page.getByText(/Waiting for review/).first()).toBeVisible()
}
test('grant UI, earlier PATCH refused, edit reason fresh, removal confirmed with its own reason', async ({ page }) => {
  const panel = await staff(page)
  await expect(panel.getByLabel('Applies to')).toHaveValue(`lesson:${ids.lesson}`)
  await expect(panel.locator('option[value="final"]')).toHaveCount(0)
  await panel.getByLabel('New deadline (Guam)').fill(day(3))
  await panel.getByLabel('Reason', { exact: true }).fill('Travel approved')
  await panel.getByRole('button', { name: 'Grant extension', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Extension saved')
  let row = panel.locator('ul[aria-label="Extensions"] > li').filter({ hasText: 'Travel approved' })
  await expect(row).toContainText('Review lesson 1')
  await expect(row).toContainText('Granted by QA Admin')
  await expect(row).not.toContainText('staff #')
  await row.getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(panel.getByLabel('Reason', { exact: true })).toHaveValue('')
  await panel.getByLabel('New deadline (Guam)').fill(day(-1))
  await panel.getByLabel('Reason', { exact: true }).fill('Earlier correction')
  await panel.getByRole('button', { name: 'Save extension change' }).click()
  await expect(panel.getByRole('alert')).toContainText('must extend')
  await panel.getByLabel('New deadline (Guam)').fill(day(4))
  await panel.getByLabel('Reason', { exact: true }).fill('More time approved')
  await panel.getByRole('button', { name: 'Save extension change' }).click()
  await expect(panel.getByRole('status')).toContainText('Extension saved')
  row = panel.locator('ul[aria-label="Extensions"] > li').filter({ hasText: 'More time approved' })
  await row.getByRole('button', { name: 'Remove', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Remove extension?' })
  await expect(dialog.getByLabel('Removal reason')).toHaveValue('')
  await dialog.getByLabel('Removal reason').fill('No longer required')
  await dialog.getByRole('button', { name: 'Confirm removal' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(panel.getByRole('status')).toContainText('History kept')
  row = panel.locator('ul[aria-label="Extensions"] > li').filter({ hasText: 'No longer required' })
  await row.getByText('Extension history (3)').click()
  await expect(row).toContainText('Travel approved')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
