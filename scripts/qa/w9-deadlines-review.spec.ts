test('a final grant refreshes the saved plan with no draft and keeps the pace start draft', async ({ page }) => {
  const panel = await staff(page, true)
  const pace = page.locator('[data-region="staff-pace"]')
  const plan = page.getByRole('region', { name: 'Student learning plan' })
  const start = pace.getByLabel('Personal start date')
  await start.fill(day(2))
  await expect(plan.getByRole('textbox', { name: 'Plan title' })).toHaveCount(0)
  await panel.getByLabel('New deadline (Guam)').fill(day(42))
  await panel.getByLabel('Reason', { exact: true }).fill('Final date review')
  await panel.getByRole('button', { name: 'Grant extension', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Extension saved')
  await expect(start).toHaveValue(day(2))
  await expect(pace).toContainText('Your unsaved choices are kept')
  const response = await page.request.get(`/api/v1/enrollments/${ids.pace.enrollment}/learning_plan`, { headers: { Authorization: 'Bearer test_token_1' } })
  expect(response.ok()).toBe(true)
  const date = (await response.json()).learning_plan.target_date
  expect(date).toBe(day(42))
  await expect(plan).toContainText(new Date(`${date}T00:00:00+10:00`).toLocaleDateString('en-US', { timeZone: 'Pacific/Guam', year: 'numeric', month: 'short', day: 'numeric' }))
})

test('removing the edited grant clears its draft and a stale PATCH cannot restore it', async ({ page }) => {
  const panel = await staff(page)
  await panel.getByLabel('Applies to').selectOption(`lesson:${ids.lesson}`)
  await panel.getByLabel('New deadline (Guam)').fill(day(3))
  await panel.getByLabel('Reason', { exact: true }).fill('Temporary leave')
  await panel.getByRole('button', { name: 'Grant extension', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Extension saved')
  const row = panel.getByRole('list', { name: 'Extensions', exact: true }).locator(':scope > li').last()
  await row.getByRole('button', { name: 'Edit', exact: true }).click()
  await panel.getByLabel('Reason', { exact: true }).fill('Obsolete correction')
  const grants = await page.request.get(`/api/v1/enrollments/${ids.extended.enrollment}/extensions`, { headers: { Authorization: 'Bearer test_token_1' } })
  const id = (await grants.json()).extensions.at(-1).id
  await row.getByRole('button', { name: 'Remove', exact: true }).click()
  const modal = page.getByRole('dialog')
  await modal.getByLabel('Removal reason').fill('Leave ended')
  await modal.getByRole('button', { name: 'Confirm removal' }).click()
  await expect(panel.getByRole('status')).toContainText('Extension removed')
  await expect(panel.getByLabel('Reason', { exact: true })).toHaveValue('')
  await expect(panel.getByRole('button', { name: 'Save extension change' })).toHaveCount(0)
  const stale = await page.request.patch(`/api/v1/enrollments/${ids.extended.enrollment}/extensions/${id}`, { headers: { Authorization: 'Bearer test_token_1' }, data: { reason: 'Stale correction' } })
  expect(stale.status()).toBe(404)
  await expect(row).toContainText('Removed')
  await expect(row).toContainText('Extension history (2)')
})


