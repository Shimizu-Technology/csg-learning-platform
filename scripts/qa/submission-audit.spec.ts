import { test, expect } from '../../web/node_modules/@playwright/test/index.mjs'

for (const theme of ['light', 'dark']) {
  test(`audit decisions and saved MWF outline: ${theme}`, async ({ page }) => {
    await page.addInitScript((value) => localStorage.setItem('csg-learn:theme', value), theme)
    await page.goto('/modules/1?cohort_id=1&qa_user=3')
    await expect(page.getByRole('heading', { name: 'Monday', exact: true })).toBeVisible()
    const studentBefore = await page.locator('main').innerText()
    await page.goto('/admin/content/submission-audit?qa_user=1')
    await expect(page.getByRole('heading', { name: 'Submission audit', exact: true })).toBeVisible()
    await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
    await expect(page.locator('article').first()).toBeVisible()
    const row = page.locator('article').filter({ has: page.getByRole('link', { name: 'Needs a submission', exact: true }) }).first()
    const name = await row.locator('h2').innerText()
    await row.getByRole('link', { name: 'Needs a submission' }).click()
    await expect(page.getByText('Suggested submission:', { exact: false })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeDisabled()
    // Direct editor links must select the block's settings without changing it.
    await expect(page.getByRole('combobox', { name: 'Submission type' })).toBeVisible()
    await page.goto('/admin/content/submission-audit?qa_user=1')
    const target = page.locator('article').filter({ has: page.getByRole('heading', { name, exact: true }) })
    await target.getByRole('button', { name: 'Practice only — mark as reviewed' }).click()
    await expect(target).toHaveCount(0)
    await page.reload()
    await expect(page.locator('article').filter({ has: page.getByRole('heading', { name, exact: true }) })).toHaveCount(0)
    await page.goto('/admin/content?curriculum=1&open=1&pane=detail&view=calendar&qa_user=1')
    await expect(page.locator('#module-1').getByRole('heading', { name: 'Day 1 · Monday' })).toBeVisible()
    await expect(page.locator('#module-1').getByRole('heading', { name: /Tuesday|Thursday/ })).toHaveCount(0)
    await expect(page.getByText('Show empty days', { exact: false })).toHaveCount(0)
    await page.goto('/modules/1?cohort_id=1&qa_user=3')
    await expect(page.getByRole('heading', { name: 'Monday', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: /Tuesday|Thursday/ })).toHaveCount(0)
    expect(await page.locator('main').innerText()).toBe(studentBefore)
    await page.goto('/admin/content/submission-audit?qa_user=1')
    const instruction = page.locator('article').filter({ has: page.getByRole('link', { name: 'Add a companion exercise', exact: true }) }).first()
    await expect(instruction.getByRole('link', { name: 'Needs a submission', exact: true })).toHaveCount(0)
    await instruction.getByRole('link', { name: 'Add a companion exercise', exact: true }).click()
    await expect(page.locator('article[aria-current="true"]')).toHaveAttribute('aria-label', /Exercise block/)
    await expect(page.getByRole('combobox', { name: 'Submission type' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeEnabled()
    // Do not save this draft: navigate away after accepting the unload confirmation.
    page.on('dialog', (dialog) => dialog.accept())
    await page.goto('/admin/cohorts/1?tab=schedule&qa_user=1')
    await expect(page.getByRole('heading', { name: 'Classes & office hours', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: /Tuesday|Thursday/ })).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
