// Evaluate in the shared QA browser after opening a staff program profile.
// Uses the rendered controls for journeys; fixture setup stays in Ruby.
(async function studentWorkspaceQA() {
  const checks = []
  const wait = async (predicate, label) => {
    await new Promise(resolve => setTimeout(resolve, 100))
    for (let index = 0; index < 100; index++) {
      if (predicate()) return
      await new Promise(resolve => setTimeout(resolve, 100))
    }
    throw new Error(`Timed out: ${label}`)
  }
  const assert = (condition, label) => { if (!condition) throw new Error(label); checks.push(label) }
  const main = () => document.querySelector('main')
  const links = () => [...(main()?.querySelectorAll('a') || [])]
  const press = element => { if (!element) throw new Error('Control missing'); element.scrollIntoView({ block: 'center', inline: 'center' }); element.click() }
  const section = async tab => {
    press(document.querySelector(`nav[aria-label="Student page sections"] a[href$="/${tab}"]`))
    await wait(() => location.pathname.endsWith(`/${tab}`), tab)
  }
  const backTo = async path => {
    await wait(() => links().some(a => a.textContent.trim().startsWith('Back') && new URL(a.href).pathname === path), 'Back control')
    const link = links().find(a => a.textContent.trim().startsWith('Back') && new URL(a.href).pathname === path)
    assert(Boolean(link), `Explicit Back to ${path}`)
    press(link)
    await wait(() => location.pathname === path && document.querySelector('nav[aria-label="Student page sections"]'), 'return to profile')
  }
  try {
    const profile = '/admin/cohorts/1/students/3'
    await wait(() => main()?.innerText.includes('Why flagged') && links().some(a => a.textContent.includes('Grade next')), 'profile shared status')
    assert(document.documentElement.scrollWidth <= innerWidth, 'No profile horizontal overflow')
    const action = [...main().querySelectorAll('button')].find(b => b.textContent === 'Message')
    assert(action.getBoundingClientRect().height >= (innerWidth < 768 ? 44 : 36), 'Reachable profile Message target')
    const metrics = ['Learning progress', 'Work waiting', 'Redo open', 'Open support', 'Recordings completed', 'Lesson videos completed']
    const cards = Object.fromEntries(metrics.map(label => [label, links().find(a => [...a.querySelectorAll('p')].some(p => p.textContent === label))]))
    assert(Object.values(cards).every(Boolean), 'All six metrics are real links')
    press(links().find(a => a.textContent.includes('Grade next')))
    await wait(() => location.pathname.startsWith('/admin/submissions/'), 'grade next')
    assert(new URLSearchParams(location.search).get('cohort_id') === '1', 'Grade next keeps enrollment')
    await backTo(`${profile}/overview`)
    await wait(() => main()?.innerText.includes('Why flagged'), 'profile reload')
    press(cards['Work waiting'].isConnected ? cards['Work waiting'] : links().find(a => a.textContent.includes('Work waiting')))
    await wait(() => location.search.includes('filter=ungraded') && main()?.innerText.includes('All submitted work'), 'work metric')
    assert(links().filter(a => a.href.includes('/submissions/')).length > 0, 'Waiting work filter opens reviewable work')
    await section('overview')
    press(links().find(a => a.textContent.includes('Redo open')))
    await wait(() => location.search.includes('filter=redo') && main()?.innerText.includes('Redo'), 'redo metric')
    assert(!main().innerText.includes('Waiting for review'), 'Redo filter excludes pending history')
    await section('overview')
    press(links().find(a => a.textContent.includes('Recordings completed')))
    await wait(() => location.hash === '#recordings' && document.activeElement?.id === 'recordings', 'recordings focus')
    assert(document.activeElement.id === 'recordings', 'Recordings metric focuses explaining section')
    await section('overview')
    press(links().find(a => a.textContent.includes('Lesson videos completed')))
    await wait(() => location.hash === '#lesson-videos' && document.activeElement?.id === 'lesson-videos', 'lesson video focus')
    assert(document.activeElement.id === 'lesson-videos', 'Lesson video metric focuses explaining section')
    await section('overview')
    press(links().find(a => a.textContent.includes('Open support')))
    await wait(() => location.pathname.endsWith('/support') && links().some(a => a.textContent === 'Open Support'), 'open support metric')
    assert(location.pathname.endsWith('/support'), 'Open support metric opens support history')
    await section('overview')
    press(links().find(a => a.textContent.includes('Learning progress')))
    await wait(() => [...document.querySelectorAll('[aria-label="Student learning plan"] a')].some(a => a.textContent === 'QA Lab 1.1.1'), 'milestone lesson')
    press([...document.querySelectorAll('[aria-label="Student learning plan"] a')].find(a => a.textContent === 'QA Lab 1.1.1'))
    await wait(() => location.pathname.startsWith('/lessons/') && main()?.innerText.includes('Synthetic garden counter'), 'milestone lesson detail')
    assert(new URLSearchParams(location.search).get('cohort_id') === '1', 'Milestone link keeps cohort')
    await backTo(`${profile}/learning`)
    await section('overview')
    press(links().find(a => a.dataset.recordLink === 'module'))
    await wait(() => location.pathname.startsWith('/modules/') && main()?.innerText.includes('QA Lab'), 'module lessons')
    await backTo(`${profile}/overview`)
    await section('communication')
    await wait(() => main()?.innerText.includes('QA workspace channel activity'), 'communication history')
    assert(main().innerText.includes('QA workspace message'), 'Recent permitted DM content shown')
    const message = links().find(a => a.href.includes('/messages/dm/') && a.textContent.includes('QA workspace message'))
    assert(new URL(message.href).searchParams.has('return_to'), 'Message URL preserves return path')
    press(message)
    await wait(() => location.pathname.startsWith('/messages/dm/') && main()?.innerText.includes('QA workspace message'), 'message drilldown')
    await backTo(`${profile}/communication`)
    await wait(() => links().some(a => a.href.includes('booking_id=')), 'meeting row')
    press(links().find(a => a.href.includes('booking_id=')))
    await wait(() => location.pathname === '/admin/meetings' && document.querySelector('[id^="booking-"]'), 'meeting drilldown')
    assert(document.querySelector('[id^="booking-"]') !== null, 'Exact meeting renders')
    await backTo(`${profile}/communication`)
    await wait(() => main()?.innerText.includes('QA workspace channel activity'), 'channel row')
    press(links().find(a => a.href.includes('/messages/') && !a.href.includes('/dm/') && a.textContent.includes('QA workspace channel activity')))
    await wait(() => /^\/messages\/\d+$/.test(location.pathname) && main()?.innerText.includes('QA workspace channel activity'), 'channel drilldown')
    await backTo(`${profile}/communication`)
    await wait(() => document.querySelector('[aria-label="Switch student enrollment"]'), 'enrollment switcher')
    const choose = value => { const select = document.querySelector('[aria-label="Switch student enrollment"]'); select.value = value; select.dispatchEvent(new Event('change', { bubbles: true })) }
    choose('2')
    await wait(() => location.pathname === '/admin/cohorts/2/students/3/communication' && main()?.innerText.includes('No recent class chat activity'), 'other enrollment')
    assert(!main().innerText.includes('QA workspace channel activity'), 'Switch clears previous enrollment communication')
    choose('1')
    await wait(() => location.pathname === `${profile}/communication` && main()?.innerText.includes('QA workspace channel activity'), 'original enrollment')
    await section('support')
    await wait(() => links().some(a => a.textContent === 'Open Support'), 'Support link')
    const support = links().find(a => a.textContent === 'Open Support')
    assert(support.getBoundingClientRect().height >= 44, 'Support target at least 44px')
    press(support)
    await wait(() => location.pathname === '/admin/support' && main()?.innerText.includes('Needs attention'), 'Support scope')
    assert(new URLSearchParams(location.search).get('cohort_id') === '1', 'Support keeps cohort')
    await backTo(`${profile}/support`)
    await section('overview')
    await wait(() => links().some(a => a.textContent === 'View as student'), 'preview entry')
    press(links().find(a => a.textContent === 'View as student'))
    await wait(() => main()?.innerText.includes('Continue learning'), 'preview Today')
    assert(document.documentElement.scrollWidth <= innerWidth, 'No preview horizontal overflow')
    const previewLinks = links().filter(a => a.href.includes('/lessons/') || a.href.includes('/modules/'))
    assert(previewLinks.every(a => a.pathname.startsWith('/admin/cohorts/1/student-view/')), 'Rendered lesson/module hrefs stay in preview, including new tabs')
    press(links().find(a => a.textContent === 'Continue learning'))
    await wait(() => location.pathname.includes('/student-view/lessons/') && main()?.innerText.includes('Synthetic garden counter'), 'preview lesson')
    assert(new URLSearchParams(location.search).get('student_id') === '3', 'Continue retains preview student')
    const writes = [...main().querySelectorAll('button')].filter(b => /^(Submit|Mark complete|Check answer)/.test(b.textContent.trim()))
    assert(writes.every(b => b.disabled), 'Preview lesson is read only')
    press(links().find(a => a.textContent === 'Back to Learn'))
    await wait(() => location.pathname.includes('/student-view/materials') && main()?.innerText.includes('QA Lab'), 'preview Learn')
    const today = [...document.querySelectorAll('a')].find(a => a.textContent.trim() === 'Today')
    press(today)
    await wait(() => main()?.innerText.includes('Continue learning'), 'preview Today again')
    press(links().find(a => a.href.includes('/student-view/modules/')))
    await wait(() => location.pathname.includes('/student-view/modules/') && main()?.innerText.includes('QA Lab'), 'preview module')
    press(links().find(a => a.href.includes('/student-view/lessons/')))
    await wait(() => location.pathname.includes('/student-view/lessons/') && main()?.innerText.includes('Synthetic garden counter'), 'preview module lesson')
    assert(location.pathname.includes('/student-view/lessons/'), 'Module lesson remains in preview')
    return { passed: true, checks, url: location.href, viewport: innerWidth, theme: document.documentElement.dataset.theme }
  } catch (error) { return { passed: false, checks, error: error.message, url: location.href, text: main()?.innerText.slice(-900), viewport: innerWidth, theme: document.documentElement.dataset.theme } }
})()
